#!/usr/bin/env python3
"""Rebuild the generated stats block in README.md from reports/*.md.

Only the text between <!-- SOC-STATS:START --> and <!-- SOC-STATS:END -->
is replaced; the rest of the README is left alone.
Usage: python scripts/build_readme.py [--check]
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- SOC-STATS:START -->", "<!-- SOC-STATS:END -->"

ALIASES = {
    "endpoint xdr": "XDR",
    "mail platform logs": "Email",
    "cloud": "Cloud audit",
    "entra sign-in/graph audit logs": "Cloud audit",
}

TITLE_RE = re.compile(r"^#\s+(.+)$", re.M)
TOOLS_RE = re.compile(r"\*\*Tools:\*\*\s*([^|]+?)\s*(?:\||$)", re.M)
TASKS_RE = re.compile(r"(\d+)\s*/\s*(\d+)\s*tasks")
VERDICT_RE = re.compile(r"\*\*Verdict:\*\*\s*([A-Za-z ]+?)\s*[—\-]")


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    header = "\n".join(text.splitlines()[:6])
    title = TITLE_RE.search(text)
    tools = TOOLS_RE.search(header)
    tasks = TASKS_RE.search(header)
    verdict = VERDICT_RE.search(header)
    return {
        "num": int(path.name.split("-", 1)[0]),
        "file": path.name,
        "title": title.group(1).strip() if title else path.stem,
        "tools": list(dict.fromkeys(ALIASES.get(t.strip().lower(), t.strip()) for t in tools.group(1).split(","))) if tools else [],
        "solved": int(tasks.group(1)) if tasks else 0,
        "total": int(tasks.group(2)) if tasks else 0,
        "verdict": verdict.group(1).strip() if verdict else "Unknown",
        "first_blood": "first blood" in header.lower(),
    }


def render(ops: list[dict]) -> str:
    n = len(ops)
    tp = sum(o["verdict"].lower() == "true positive" for o in ops)
    fb = [o for o in ops if o["first_blood"]]
    solved = sum(o["solved"] for o in ops)
    total = sum(o["total"] for o in ops)
    pct = f"{100 * solved / total:.1f}%" if total else "n/a"
    tools = Counter(t for o in ops for t in o["tools"])
    tool_line = " · ".join(f"{t} ({c})" for t, c in tools.most_common())

    lines = [
        START,
        "<!-- Generated by scripts/build_readme.py from reports/*.md. Do not edit by hand. -->",
        "## At a glance",
        "",
        "| Metric | Value |",
        "| :--- | :--- |",
        f"| Operations written up | **{n}** |",
        f"| Closed True Positive | **{tp}/{n}** |",
        f"| Tasks answered correctly | **{solved}/{total}** ({pct}) |",
        f"| First Blood | **{len(fb)}** |",
        f"| Consoles used | {tool_line} |",
        "",
        "<details><summary>Index of all operations</summary>",
        "",
        "| # | Operation | Tools | Result |",
        "| ---: | --- | --- | --- |",
    ]
    for o in sorted(ops, key=lambda o: o["num"]):
        result = f"{o['solved']}/{o['total']}" + (" · First Blood" if o["first_blood"] else "")
        lines.append(
            f"| {o['num']} | [{o['title']}](reports/{o['file']}) | {', '.join(o['tools'])} | {result} |"
        )
    lines += ["", "</details>", END]
    return "\n".join(lines)


def main() -> int:
    files = sorted((ROOT / "reports").glob("[0-9]*.md"))
    ops = [parse(f) for f in files]
    readme = ROOT / "README.md"
    original = readme.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(original):
        print("Markers not found in README.md", file=sys.stderr)
        return 1
    updated = pattern.sub(lambda _m: render(ops), original)
    if "--check" in sys.argv:
        return 0 if updated == original else 1
    if updated != original:
        readme.write_text(updated, encoding="utf-8", newline="\n")
        print(f"README.md updated ({len(ops)} operations).")
    else:
        print("README.md already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
